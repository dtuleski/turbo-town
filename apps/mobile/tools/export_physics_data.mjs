#!/usr/bin/env node
// Exports the web data for the physics games (Space Entry, Mini Golf, Bond & Burn) to Dart
// sources, plus golden fixtures: outputs of the real web TypeScript for the Dart ports to match.
//
// Usage (from apps/mobile): <path-to>/apps/web/node_modules/.bin/tsx tools/export_physics_data.mjs
// `tsx` is not installed in the worktree; the main checkout's apps/web has it.
// Output (committed):
//   lib/game/data/physics_data.g.dart
//   test/fixtures/physics_web_golden.json
//
// Random-driven web functions are run with Math.random replaced by a small LCG, so the Dart
// tests can replay the same sequence (test/helpers/lcg_random.dart) and expect the same output.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', 'web', 'src', 'utils');
const dataDir = join(here, '..', 'lib', 'game', 'data');
const fixtureDir = join(here, '..', 'test', 'fixtures');
mkdirSync(dataDir, { recursive: true });
mkdirSync(fixtureDir, { recursive: true });

const seCfg = await import(join(web, 'spaceEntryConfig.ts'));
const seZones = await import(join(web, 'spaceEntryLandingZones.ts'));
const sePhys = await import(join(web, 'spaceEntryPhysics.ts'));
const sePuz = await import(join(web, 'spaceEntryPuzzles.ts'));
const golfData = await import(join(web, 'miniGolfData.ts'));
const golfPhys = await import(join(web, 'miniGolfPhysics.ts'));
const bbData = await import(join(web, 'bondAndBurnData.ts'));
const bbLogic = await import(join(web, 'bondAndBurnLogic.ts'));

/** LCG shared with test/helpers/lcg_random.dart. */
function withSeed(seed, fn) {
  let x = seed >>> 0;
  const original = Math.random;
  Math.random = () => {
    x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
    return x / 4294967296;
  };
  try {
    return fn();
  } finally {
    Math.random = original;
  }
}

// ── Dart data file ──────────────────────────────────────────────────────────
function dartConst(name, doc, value) {
  const json = JSON.stringify(value);
  if (json.includes("'''")) throw new Error(`${name}: content contains a triple quote`);
  return `// ${doc}\nconst String ${name} = r'''${json}''';\n`;
}

const dartData =
  `// GENERATED by tools/export_physics_data.mjs from apps/web/src/utils. Do not edit.\n` +
  `// JSON for the physics games; parsed by lib/game/<game>/*.dart.\n\n` +
  dartConst('kSpaceEntryDataJson', 'spaceEntryConfig.ts + spaceEntryLandingZones.ts.', {
    configs: seCfg.DIFFICULTY_CONFIGS,
    animationDurationMs: seCfg.ANIMATION_DURATION_MS,
    maxGameTimeSeconds: seCfg.MAX_GAME_TIME_SECONDS,
    zones: seZones.LANDING_ZONES,
  }) +
  '\n' +
  dartConst('kMiniGolfDataJson', 'miniGolfData.ts: PHYSICS, COURSES, DIFFICULTY_CONFIGS.', {
    physics: golfData.PHYSICS,
    courses: golfData.COURSES,
    configs: golfData.DIFFICULTY_CONFIGS,
  }) +
  '\n' +
  dartConst('kBondAndBurnDataJson', 'bondAndBurnData.ts: elements, recipes, configs, periodic table.', {
    elements: bbData.ELEMENTS,
    recipes: bbData.RECIPES,
    configs: bbData.DIFFICULTY_CONFIGS,
    table: bbData.PERIODIC_TABLE_FULL,
    tableMaxRow: bbData.PERIODIC_TABLE_MAX_ROW,
  });
writeFileSync(join(dataDir, 'physics_data.g.dart'), dartData);

// ── Golden fixtures ─────────────────────────────────────────────────────────
const DIFFS = ['easy', 'medium', 'hard'];
const golden = {};

// Space Entry: predictLanding over a grid of inputs.
{
  const zones = [seZones.LANDING_ZONES[0], seZones.LANDING_ZONES[3], seZones.LANDING_ZONES.at(-1)];
  const angles = [0, 3, 6.5, 8, 11, 20];
  const thrusterOffsets = [-20, 0, 15];
  const laterals = [-3, 0, 2.5];
  const turbulences = [0, 0.25];
  const rows = [];
  for (const d of DIFFS) {
    const cfg = seCfg.DIFFICULTY_CONFIGS[d];
    zones.forEach((zone) => {
      for (const a of angles) for (const to of thrusterOffsets) for (const l of laterals) for (const t of turbulences) {
        const thr = cfg.optimalThrusterPower + to;
        const r = sePhys.predictLanding(zone.latitude, zone.longitude, a, thr, l, cfg, t);
        rows.push({
          d, z: seZones.LANDING_ZONES.indexOf(zone), a, thr, l, t,
          out: [r.predictedLat, r.predictedLng, r.distanceKm, r.accuracy, r.heatShieldRemaining, r.outcome],
        });
      }
    });
  }
  golden.spacePredict = rows;
  golden.haversine = [
    [0, 0, 0, 90], [10, 20, 30, 40], [-33.9249, 18.4241, 31.5, 35.5], [89, 179, -89, -179],
  ].map(([a, b, c, d]) => ({ in: [a, b, c, d], out: sePhys.haversineDistance(a, b, c, d) }));
  const degradation = [];
  for (const d of DIFFS) for (const angle of [0, 5, 7.5, 40]) {
    degradation.push({ d, angle, out: sePhys.calculateHeatShieldDegradation(angle, seCfg.DIFFICULTY_CONFIGS[d]) });
  }
  golden.spaceDegradation = degradation;
}

// Space Entry puzzles with a seeded Math.random.
{
  const rows = [];
  for (let seed = 1; seed <= 12; seed++) {
    for (const d of DIFFS) {
      rows.push({ seed, d, kind: 'angle', puzzle: withSeed(seed, () => sePuz.generateAnglePuzzle(d)) });
      rows.push({ seed, d, kind: 'lateral', puzzle: withSeed(seed, () => sePuz.generateLateralPuzzle(d, 0)) });
    }
    for (const d of ['medium', 'hard']) {
      rows.push({ seed, d, kind: 'thruster', puzzle: withSeed(seed, () => sePuz.generateThrusterPuzzle(d)) });
    }
  }
  golden.spacePuzzles = rows;
}

// Mini Golf.
{
  golden.golfPhysics = golfData.PHYSICS;
  golden.golfEnv = [];
  for (let seed = 1; seed <= 8; seed++) {
    for (const d of DIFFS) {
      golden.golfEnv.push({ seed, d, env: withSeed(seed, () => golfPhys.generateEnvironment(d)) });
    }
  }
  golden.golfScoreNames = [-4, -3, -2, -1, 0, 1, 2, 3, 5].map((diff) => ({
    diff, out: golfData.getScoreName(diff + 3, 3),
  }));

  const S = 1.5;
  const scale = (hole) => ({
    ...hole,
    ball: { x: hole.ball.x * S, y: hole.ball.y * S },
    cup: { x: hole.cup.x * S, y: hole.cup.y * S },
    walls: hole.walls.map((w) => ({
      start: { x: w.start.x * S, y: w.start.y * S },
      end: { x: w.end.x * S, y: w.end.y * S },
    })),
    obstacles: hole.obstacles.map((o) => ({
      ...o,
      x: o.x * S, y: o.y * S,
      width: o.width ? o.width * S : undefined,
      height: o.height ? o.height * S : undefined,
      radius: o.radius ? o.radius * S : undefined,
    })),
    width: 600, height: 600,
  });
  const envs = [
    { windSpeed: 0, windDirection: 0, temperature: 20, altitude: 0 },
    { windSpeed: 12, windDirection: 30, temperature: 38, altitude: 1200 },
    { windSpeed: 7, windDirection: 200, temperature: 0, altitude: 2500 },
  ];
  const snapshots = [1, 5, 30, 120, 300, 700];
  const sims = [];
  for (const course of golfData.COURSES) {
    course.holes.forEach((hole, hi) => {
      const sh = scale(hole);
      const toCup = Math.atan2(sh.cup.y - sh.ball.y, sh.cup.x - sh.ball.x);
      const shots = [
        { angle: toCup, power: 9 },
        { angle: toCup + 0.4, power: 12.5 },
        { angle: toCup - 1.1, power: 5 },
      ];
      envs.forEach((env, ei) => shots.forEach((shot, si) => {
        let ball = {
          pos: { ...sh.ball },
          vel: { x: Math.cos(shot.angle) * shot.power, y: Math.sin(shot.angle) * shot.power },
          inSand: false, inWater: false, sunk: false,
        };
        const states = [];
        for (let tick = 0; tick < 700; tick++) {
          ball = golfPhys.physicsTick(ball, sh, tick * golfData.PHYSICS.TICK_RATE, env);
          if (snapshots.includes(tick + 1)) {
            states.push([tick + 1, ball.pos.x, ball.pos.y, ball.vel.x, ball.vel.y, ball.inSand, ball.inWater, ball.sunk]);
          }
        }
        sims.push({ course: course.id, hole: hi, env: ei, shot: si, angle: shot.angle, power: shot.power, states });
      }));
    });
  }
  golden.golfEnvs = envs;
  golden.golfSims = sims;

  const windmill = golfData.COURSES.flatMap((c) => c.holes).flatMap((h) => h.obstacles).find((o) => o.type === 'windmill');
  golden.golfWindmill = [0, 100, 777.5, 5000, 20000].map((time) => ({
    time,
    walls: golfPhys.getWindmillBladeWalls(windmill, time).map((w) => [w.end.x, w.end.y]),
  }));
}

// Bond & Burn.
{
  golden.bbRandom = [];
  for (let seed = 1; seed <= 10; seed++) {
    for (const d of DIFFS) {
      const cfg = bbData.DIFFICULTY_CONFIGS[d];
      const ids = cfg.availableRecipeIds;
      const draws = withSeed(seed, () => {
        const out = [];
        for (let i = 0; i < 12; i++) {
          const recipe = i % 3 === 2 ? undefined : bbData.getRecipeById(ids[i % ids.length]);
          out.push(bbData.getRandomElement(cfg, recipe).symbol);
        }
        return out;
      });
      golden.bbRandom.push({ seed, d, draws });
    }
  }
  golden.bbScores = [];
  for (const recipe of bbData.RECIPES) {
    for (const d of DIFFS) for (const time of [0, 5, 12.5, 20, 33]) for (const combo of [1, 2, 3, 6]) {
      golden.bbScores.push({
        id: recipe.id, d, time, combo,
        out: bbLogic.calculateRecipeScore(recipe, time, combo, d),
      });
    }
  }
  golden.bbTables = Object.fromEntries(DIFFS.map((d) => [d, bbData.getPeriodicTable(d).map((e) => e.symbol)]));
  golden.bbFinal = [0, 100, 7999, 8000, 12000].map((s) => ({ s, out: bbLogic.calculateFinalScore(s) }));
}

writeFileSync(join(fixtureDir, 'physics_web_golden.json'), JSON.stringify(golden));
console.log('Wrote physics_data.g.dart and physics_web_golden.json', {
  spacePredict: golden.spacePredict.length,
  spacePuzzles: golden.spacePuzzles.length,
  golfSims: golden.golfSims.length,
  bbScores: golden.bbScores.length,
});
