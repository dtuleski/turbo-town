#!/usr/bin/env node
// Exports the web quiz and word-game data to Dart sources, plus a counts file
// the data-parity tests compare against.
//
// Usage (from apps/mobile): <path-to>/apps/web/node_modules/.bin/tsx tools/export_quiz_data.mjs
// `tsx` is not installed in the worktree; the main checkout's apps/web has it.
// Output (committed):
//   lib/game/data/{geo,history,civics,hangman,word_puzzle}_data.g.dart
//   test/fixtures/quiz_web_counts.json
//   test/fixtures/pronunciation_golden.json (web scoring outputs for the Dart port)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', 'web', 'src', 'utils');
const dataDir = join(here, '..', 'lib', 'game', 'data');
const fixtureDir = join(here, '..', 'test', 'fixtures');
mkdirSync(dataDir, { recursive: true });
mkdirSync(fixtureDir, { recursive: true });

const geo = await import(join(web, 'geoQuizData.ts'));
const history = await import(join(web, 'historyQuizData.ts'));
const civics = await import(join(web, 'civicsQuizData.ts'));
const hangman = await import(join(web, 'hangmanData.ts'));
const pron = await import(join(web, 'pronunciationScoring.ts'));

// WORD_LISTS_BY_LOCALE is not exported; evaluate the object literal from source.
const wpSource = readFileSync(join(web, 'wordPuzzleUtils.ts'), 'utf8');
const start = wpSource.indexOf('const WORD_LISTS_BY_LOCALE');
const open = wpSource.indexOf('= {', start) + 2;
const end = wpSource.indexOf('\nfunction getWordLists', start);
const wordLists = new Function(`return (${wpSource.slice(open, end).trim()})`)();

function writeDart(file, constName, doc, value) {
  const json = JSON.stringify(value);
  if (json.includes("'''")) throw new Error(`${file}: content contains a triple quote`);
  const body =
    `// GENERATED by tools/export_quiz_data.mjs from apps/web/src/utils. Do not edit.\n` +
    `// ${doc}\n` +
    `const String ${constName} = r'''${json}''';\n`;
  writeFileSync(join(dataDir, file), body);
}

writeDart('geo_data.g.dart', 'kGeoDataJson', 'geoQuizData.ts: countries, states, silhouettes.', {
  countries: geo.COUNTRIES,
  states: geo.STATES,
  silhouettes: geo.COUNTRY_SILHOUETTES,
});
writeDart('history_data.g.dart', 'kHistoryDataJson', 'historyQuizData.ts: HISTORY_EVENTS.', {
  events: history.HISTORY_EVENTS,
});
writeDart('civics_data.g.dart', 'kCivicsDataJson', 'civicsQuizData.ts: CIVICS_QUESTIONS.', {
  questions: civics.CIVICS_QUESTIONS,
});
const hangmanWords = {
  en: { easy: hangman.EASY_WORDS, medium: hangman.MEDIUM_WORDS, hard: hangman.HARD_WORDS },
  es: { easy: hangman.EASY_WORDS_ES, medium: hangman.MEDIUM_WORDS_ES, hard: hangman.HARD_WORDS_ES },
  pt: { easy: hangman.EASY_WORDS_PT, medium: hangman.MEDIUM_WORDS_PT, hard: hangman.HARD_WORDS_PT },
};
writeDart('hangman_data.g.dart', 'kHangmanDataJson', 'hangmanData.ts word lists per language and difficulty.', hangmanWords);
writeDart('word_puzzle_data.g.dart', 'kWordPuzzleDataJson', 'wordPuzzleUtils.ts WORD_LISTS_BY_LOCALE.', wordLists);

const countBy = (arr, key) => {
  const out = {};
  for (const item of arr) out[item[key]] = (out[item[key]] ?? 0) + 1;
  return out;
};
const nested = (obj) =>
  Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).map(([d, l]) => [d, l.length]))]));

const counts = {
  geo: {
    countries: geo.COUNTRIES.length,
    states: geo.STATES.length,
    silhouettes: Object.keys(geo.COUNTRY_SILHOUETTES).length,
    modes: Object.keys(geo.GAME_MODES),
    difficultyModes: geo.DIFFICULTY_MODES,
  },
  history: {
    events: history.HISTORY_EVENTS.length,
    byDifficulty: countBy(history.HISTORY_EVENTS, 'difficulty'),
    withPerson: history.HISTORY_EVENTS.filter((e) => e.person).length,
    withImage: history.HISTORY_EVENTS.filter((e) => e.imageUrl).length,
    difficultyModes: history.DIFFICULTY_MODES,
  },
  civics: {
    questions: civics.CIVICS_QUESTIONS.length,
    byCategory: countBy(civics.CIVICS_QUESTIONS, 'category'),
  },
  hangman: nested(hangmanWords),
  hangmanMaxWrong: hangman.MAX_WRONG,
  hangmanRounds: hangman.ROUNDS_PER_GAME,
  wordPuzzle: nested(wordLists),
};
writeFileSync(join(fixtureDir, 'quiz_web_counts.json'), JSON.stringify(counts, null, 2) + '\n');
console.log('exported', JSON.stringify(counts));

// Golden outputs of the web pronunciation scorer, so the Dart port is checked
// against the real implementation and not only against its own reading of it.
const words = [
  'cat', 'dog', 'apple', 'queen', 'knight', 'phone', 'house', 'water', 'thought', 'judge',
  'gato', 'perro', 'ñandú', 'niño', 'lluvia', 'jardín', 'mariposa', 'cielo', 'queso', 'zorro',
  'chat', 'fromage', 'bonjour', 'oiseau', 'cane', 'gelato', 'ciao', 'scuola', 'haus', 'schmetterling',
  'wasser', 'straße', 'cão', 'pão', 'coração', 'obrigado', 'ψάρι', 'σκύλος', 'γάτα', 'νερό',
  'sky', 'why', 'yes', 'we', 'xylophone', 'wrong', 'gnome', 'aeon', 'ghost', 'cheese',
];
const spokenFor = (w) => [w, w.slice(0, -1), w + 's', 'banana', '', w.split('').reverse().join('')];
const scoreCases = [];
for (const w of words) {
  for (const spoken of spokenFor(w)) {
    for (const confidence of [undefined, 0.2, 0.9]) {
      for (const strictness of ['normal', 'strict']) {
        const r = pron.calculatePronunciationScore(w, spoken, confidence, strictness);
        scoreCases.push({
          expected: w,
          spoken,
          confidence: confidence ?? null,
          strictness,
          score: r.score,
          graded: r.graded,
          recognized: r.recognized,
          feedback: r.feedback,
          phonetic: r.phoneticScore,
          string: r.stringScore,
        });
      }
    }
  }
}
const metaphone = words.map((w) => ({ word: w, code: pron.doubleMetaphone(w) }));
const latin = [...words, 'Ελλάδα', 'мир', '', '123'].map((w) => ({ word: w, latin: pron.isLatinScript(w) }));
writeFileSync(
  join(fixtureDir, 'pronunciation_golden.json'),
  JSON.stringify({ scoreCases, metaphone, latin }) + '\n',
);
console.log('pronunciation cases', scoreCases.length);
